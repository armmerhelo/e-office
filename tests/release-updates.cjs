const assert = require('node:assert/strict');
const {prepare, record} = require('../scripts/release-updates.cjs');

const draft = prepare({from:'HEAD~2', to:'HEAD'});
assert.equal(draft.commits.length, 2);
assert.ok(draft.commits.every(commit => /^[a-f0-9]{40}$/.test(commit.hash) && commit.subject && commit.paths.length));
assert.throws(() => prepare({commits:'HEAD,HEAD'}), /unique/);
assert.throws(() => prepare({commits:'HEAD', from:'HEAD~1'}), /OR/);
assert.throws(() => prepare({from:'HEAD', to:'HEAD'}), /nonempty/);
const targeted = prepare({commits:'HEAD~2,HEAD'});
assert.equal(targeted.commits[1].hash, draft.commits[1].hash);
assert.notEqual(targeted.commits[0].hash, draft.commits[0].hash, 'targeted release excludes unrelated commits');
const existing = [{id:'legacy', date:'2026-01-01', title:'เดิม', summary:'เดิม', added:[], improved:[], fixed:[]}];
assert.throws(() => record(draft, '2026-10-28T12:00:00+07:00', existing), /Complete/);
draft.title = 'ปรับปรุงระบบ'; draft.summary = 'ใช้งานสะดวกขึ้น';
draft.commits.forEach((commit, index) => { commit.summary = `รายละเอียด ${index}`; commit.category = index ? 'fixed' : 'improved'; });
assert.throws(() => record(draft, '2026-10-28T12:00:00', existing), /timezone/);
assert.throws(() => record({...draft, commits:[draft.commits[0], draft.commits[0]]}, '2026-10-28T12:00:00Z', existing), /unique/);
const feed = record(draft, '2026-10-27T18:30:00Z', existing);
assert.equal(feed[0].date, '2026-10-28', 'release date uses Thailand timezone');
assert.deepEqual(feed[0].improved, ['รายละเอียด 0']);
assert.deepEqual(feed[0].fixed, ['รายละเอียด 1']);
assert.equal(feed[1], existing[0], 'preserves legacy history');
assert.equal(existing.length, 1, 'does not mutate existing feed');
assert.ok(!JSON.stringify(feed[0]).includes('paths'), 'internal review metadata is not published');
assert.equal(record(draft, '2026-10-28T01:30:00+07:00', feed), feed, 'retry with same timestamp does not duplicate release');
assert.throws(() => record({...draft, title:'changed'}, '2026-10-27T18:30:00Z', feed), /different content/);
const later = record(draft, '2026-10-28T02:30:00+07:00', feed);
assert.ok(later[0].id > later[1].id, 'multiple daily deployments sort newest first');
console.log('PASS deployment history: Git range/targeted commits, reviewed summaries, Thai date, preservation and idempotent recording');
